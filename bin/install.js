#!/usr/bin/env node
/**
 * hncode auto-install script
 * Creates default configuration and sets up the environment
 */

const fs = require('fs');
const path = require('path');
const os = require('os');

// Get user home directory (cross-platform)
const homeDir = os.homedir();
const configDir = path.join(homeDir, '.hncode');
const configFile = path.join(configDir, 'config.toml');
const sessionsDir = path.join(configDir, 'sessions');
const pluginsDir = path.join(configDir, 'plugins');

console.log('🚀 Setting up hncode...\n');

// Create directories if they don't exist
const dirs = [configDir, sessionsDir, pluginsDir];
for (const dir of dirs) {
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
    console.log(`✓ Created directory: ${dir}`);
  } else {
    console.log(`✓ Directory exists: ${dir}`);
  }
}

// Check if config file exists
if (!fs.existsSync(configFile)) {
  const defaultConfig = `# hncode Configuration
# Generated by hncode install script

# Default model (change this to your preferred model)
default_model = "gpt-4o-mini"

# Optional: Add providers directly here
# Uncomment and configure as needed:
# 
# [providers.openai]
# base_url = "https://api.openai.com/v1"
# api_key = "your-api-key-here"
# protocol = "openai"

# Or use environment variables:
# HNCODE_API_KEY="your-key"
# HNCODE_PROVIDER="openai"
# HNCODE_MODEL="gpt-4o-mini"

`;

  fs.writeFileSync(configFile, defaultConfig);
  console.log(`\n✅ Created default configuration at: ${configFile}`);
  console.log('\n💡 Next steps:');
  console.log('   1. Edit ~/.hncode/config.toml with your API key');
  console.log('   2. Or set environment variables:');
  console.log('      export HNCODE_API_KEY="your-key"');
  console.log('      export HNCODE_PROVIDER="openai"');
  console.log('   3. Run "hncode" to start!');
} else {
  console.log(`\nℹ️  Configuration already exists at: ${configFile}`);
  console.log('   Run "hncode init" to regenerate or edit manually.');
}

console.log('\n✨ hncode is ready to use!');

// Try to refresh environment automatically
try {
  const platform = os.platform();
  
  if (platform === 'win32') {
    // Windows: Use PowerShell to refresh environment
    const { execSync } = require('child_process');
    try {
      execSync('Refresh-Environment', { stdio: 'pipe' });
      console.log('✓ Environment refreshed automatically (PowerShell)');
    } catch (e) {
      console.log('ℹ️  To refresh environment in PowerShell:');
      console.log('   . "$env:LOCALAPPDATA\\npm\\npm.cmd"');
      console.log('   Or simply close and reopen your terminal');
    }
  } else {
    // Unix-like systems
    console.log('ℹ️  Please run one of these to refresh environment:');
    console.log('   source ~/.zshrc    # For Zsh');
    console.log('   source ~/.bashrc   # For Bash');
    console.log('   Or simply close and reopen your terminal');
  }
} catch (err) {
  console.log('ℹ️  Note: You may need to restart your terminal');
}

console.log('');
console.log('   Type "hncode --help" for available commands.\n');